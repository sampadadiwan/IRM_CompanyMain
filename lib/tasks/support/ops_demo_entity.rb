# Builds the "Northwind Capital Partners" demo entity for lib/tasks/ops_demo_entity.rake: an INR fund
# manager with a closed-ended fund carrying planted ops problems (P1–P8), an open-ended fund (reusing
# EvergreenDemoFund), an ops user, a read-only MCP service user and an OAuth token for Paperclip.
# Everything goes through the app's own services (CapitalCommitmentCreate, CapitalCallCreate/Approve,
# CapitalRemittancePaymentCreate/Verify, CapitalDistributionCreate, PortfolioInvestmentCreate) so the
# records look exactly like ones made from the screens. Development / staging only.
#
# Not one transaction: remittances and distribution payments are generated by jobs (run inline here),
# so a failure part-way leaves the entity as far as it got; the error names it so it can be deleted.
class OpsDemoEntity
  include ActiveSupport::NumberHelper

  DEFAULT_NAME = "Northwind Capital Partners".freeze
  CLOSED_FUND_NAME = "Northwind Growth Fund I".freeze
  OPEN_FUND_NAME = "Northwind India Opportunities Fund".freeze
  UNIT_TYPE = "Class A".freeze
  NOTE = "Demo data (ops_demo:seed)".freeze
  # The OAuth client name Paperclip's MCP connection presents; also the entity's only allowed MCP client
  MCP_CLIENT = "Paperclip".freeze
  CRORE = 10_000_000

  # folio, LP name, individual?, commitment in crores
  LPS = [
    ["NGF-001", "Bharat Pension Trust", false, 25],
    ["NGF-002", "Iyer Family Office", false, 20],
    ["NGF-003", "Ganga Endowment Fund", false, 15],
    ["NGF-004", "Malhotra Holdings Pvt Ltd", false, 10],
    ["NGF-005", "Seshadri Family Trust", false, 10],
    ["NGF-006", "Priya Raman", true, 8],
    ["NGF-007", "Coromandel Capital LLP", false, 7],
    ["NGF-008", "Vikram Bose", true, 5]
  ].freeze

  # Each call: % of commitment, call / due dates as days from today, and what happens to each folio.
  #   :paid      — paid in full before the due date and verified
  #   :unverified — paid in full, receipt never verified                         (P2)
  #   :unpaid    — nothing received (stays Pending; past the due date = overdue)  (P1, P3)
  # notice_not_sent lists folios whose call notice was never sent               (P4)
  CALLS = [
    { name: "Call 1 — Initial drawdown", pct: 20, call: -150, due: -120,
      folios: Hash.new(:paid) },
    { name: "Call 2 — Tarang and Nilgiri follow-on", pct: 15, call: -45, due: -15,
      folios: Hash.new(:paid).merge("NGF-004" => :unpaid, "NGF-007" => :unpaid, "NGF-005" => :unverified) },
    { name: "Call 3 — Arka Series B", pct: 10, call: -11, due: 3,
      folios: Hash.new(:paid).merge("NGF-002" => :unpaid, "NGF-003" => :unpaid, "NGF-006" => :unpaid, "NGF-008" => :unpaid),
      notice_not_sent: ["NGF-003"] }
  ].freeze

  # Folio whose onboarding is still incomplete (P5) and the one whose distribution payout is not done (P6)
  ONBOARDING_INCOMPLETE = "NGF-008".freeze
  PAYOUT_INCOMPLETE = "NGF-006".freeze

  # name, sector, shares, cost in crores, bought (days from today), quarterly growth, revalued?
  # Vayu Drones is never revalued after its purchase 9 months ago: the stale valuation (P7)
  COMPANIES = [
    ["Tarang Health Pvt Ltd", "Healthcare", 40_000, 12, -330, 0.06, true],
    ["Nilgiri Foods Pvt Ltd", "Consumer", 25_000, 8, -320, 0.03, true],
    ["Arka Mobility Pvt Ltd", "Mobility", 30_000, 10, -300, 0.08, true],
    ["Vayu Drones Pvt Ltd", "Deep Tech", 15_000, 6, -275, 0.0, false]
  ].freeze
  QUARTER_ENDS = [Date.new(2026, 3, 31), Date.new(2026, 6, 30), Date.new(2026, 9, 30)].freeze
  # The portfolio-company document waiting on e-sign for 15 days (P8)
  ESIGN_COMPANY = "Tarang Health Pvt Ltd".freeze
  ESIGN_DOC = "Shareholders Agreement Amendment — Tarang Health".freeze
  ESIGN_STUCK_DAYS = 15

  def initialize(name:, execute:, out: $stdout)
    @name = name
    @execute = execute
    @out = out
    @today = Time.zone.today
    @folios = {} # folio id => capital commitment
  end

  def run
    print_plan
    return say("DRY RUN — nothing created. Set EXECUTE=1 to build it.") unless @execute

    raise "Entity #{@name.inspect} already exists (id #{existing.id}) — delete it or pass ENTITY_NAME" if existing

    # Closed fund first, in the quiet (inline jobs, no mail) context; the open fund's builder has its own
    quietly { build_closed }
    build_open
    grant_bot_access
    issue_token
    print_summary
  rescue StandardError
    say("FAILED#{" — entity #{@entity.id} (#{@entity.name}) is part-built; delete it from /admin/entities" if @entity&.persisted?}")
    raise
  end

  private

  def existing
    @existing ||= Entity.find_by(name: @name)
  end

  # ---------- Plan ----------

  def print_plan
    say("#{@execute ? 'EXECUTE' : 'DRY RUN'}: #{@name} (Investment Fund, INR)")
    say("  Users: #{ops_email} (company_admin, approver) and #{bot_email} (employee only — the MCP service user)")
    say("  MCP: enable_mcp + mcp_enabled, roles [employee], clients [#{MCP_CLIENT}]; OAuth app #{MCP_CLIENT} and a 30-day token for the bot")
    say("  #{CLOSED_FUND_NAME}: #{LPS.size} LPs, #{inr(LPS.sum(&:last) * CRORE)} committed")
    CALLS.each { |c| say("    #{c[:name]}: #{c[:pct]}%, called #{@today + c[:call]}, due #{@today + c[:due]}") }
    say("    Distribution of #{inr(5 * CRORE)} on #{@today - 10}; portfolio #{COMPANIES.map(&:first).join(', ')}")
    say("  #{OPEN_FUND_NAME}: built by EvergreenDemoFund (INR, private portfolio)")
    say("  Planted problems:")
    planted.each { |id, text| say("    #{id} #{text}") }
  end

  # The planted problems as [id, description] — printed in the plan and the summary
  def planted
    [
      ["P1", "Call 2 past due, nothing received: #{folios_with(1, :unpaid).join(', ')}"],
      ["P2", "Call 2 paid but receipt not verified: #{folios_with(1, :unverified).join(', ')}"],
      ["P3", "Call 3 due #{@today + 3}, not yet paid (notified): #{(folios_with(2, :unpaid) - CALLS[2][:notice_not_sent]).join(', ')}"],
      ["P4", "Call 3 notice never sent: #{CALLS[2][:notice_not_sent].join(', ')}"],
      ["P5", "Onboarding not completed: #{ONBOARDING_INCOMPLETE}"],
      ["P6", "Distribution payout not completed, payment date #{@today - 10}: #{PAYOUT_INCOMPLETE}"],
      ["P7", "Stale valuation (only the cost valuation, #{@today + COMPANIES.last[4]}): #{COMPANIES.reject(&:last).map(&:first).join(', ')}"],
      ["P8", "E-sign requested #{ESIGN_STUCK_DAYS} days ago, still pending: #{ESIGN_DOC}"],
      ["—", "Call 1 fully paid and verified: a correct sweep raises nothing for it"]
    ]
  end

  def folios_with(call_index, outcome)
    LPS.map(&:first).select { |f| CALLS[call_index][:folios][f] == outcome }
  end

  # ---------- Build: entity, users, closed fund ----------

  # Jobs run inline (remittance and distribution-payment generation must finish before payments);
  # delayed jobs and mail are dropped, so no investor is emailed and no paid third-party check runs
  def quietly
    adapter = ActiveJob::Base.queue_adapter
    deliveries = ActionMailer::Base.perform_deliveries
    ActiveJob::Base.queue_adapter = EvergreenDemoFund::InlineDropDelayedAdapter.new(method(:say))
    ActionMailer::Base.perform_deliveries = false
    yield
  ensure
    ActiveJob::Base.queue_adapter = adapter
    ActionMailer::Base.perform_deliveries = deliveries
  end

  def build_closed
    create_entity
    create_users
    create_closed_fund
    create_commitments
    create_portfolio
    CALLS.each { |spec| create_call(spec) }
    create_distribution
    create_stuck_esign_document
  end

  def create_entity
    @entity = Entity.create!(name: @name, entity_type: "Investment Fund", primary_email: "ops@#{domain}", currency: "INR", units: "Crores")
    # The modules the demo touches, plus MCP (the CapHive-admin gate, level 1 in McpController)
    %i[enable_funds enable_units enable_fund_portfolios enable_investors enable_kycs enable_documents
       enable_account_entries enable_kpis enable_evergreen_funds enable_mcp].each { |p| @entity.permissions.set(p) }
    @entity.save!(validate: false)
    # MCP gates 2–4: entity switch on, the employee role allowed, and only the Paperclip client
    setting = @entity.entity_setting || @entity.build_entity_setting
    setting.mcp_enabled = true
    setting.mcp_allowed_roles_list = %w[employee]
    setting.mcp_allowed_clients_list = [MCP_CLIENT]
    setting.save!(validate: false)
    say("  Entity #{@entity.id} created")
  end

  def create_users
    @ops = new_user("Ops", "Lead", ops_email, password: "password", permissions: User.permissions.keys)
    %i[company_admin approver].each { |r| @ops.add_role(r) }
    # The service user keeps only the employee role setup_defaults gives it: Pundit then limits every MCP
    # query to the funds it is granted (FundScopes.for_employee) — see grant_bot_access
    @bot = new_user("Paperclip", "Bot", bot_email, password: SecureRandom.hex(24))
    say("  Users #{@ops.email} (#{@ops.id}), #{@bot.email} (#{@bot.id})")
  end

  def new_user(first_name, last_name, email, password:, permissions: nil)
    attrs = { entity: @entity, first_name:, last_name:, email:, password:, call_code: "91", phone: "9876543210",
              accept_terms: true }
    attrs[:permissions] = permissions if permissions
    User.create!(attrs)
  end

  def create_closed_fund
    start = @today - 1.year
    @fund = Fund.create!(entity: @entity, name: CLOSED_FUND_NAME, currency: "INR", unit_types: UNIT_TYPE, category: "Category II",
                         start_date: start, first_close_date: start, details: NOTE)
    say("  Fund #{@fund.id} #{@fund.name}")
  end

  # One folio per LP through CapitalCommitmentCreate (which also grants the LP access to the fund)
  def create_commitments
    LPS.each do |folio_id, name, individual, crores|
      investor = new_investor(name)
      kyc = approved_kyc(investor, individual)
      cc = CapitalCommitment.new(entity: @entity, fund: @fund, investor:, investor_kyc: kyc, folio_id:, unit_type: UNIT_TYPE,
                                 fund_close: "First Close", folio_currency: "INR", commitment_date: @today - 1.year,
                                 # The original amount: set_committed_amount derives folio_committed_amount_cents from it (+ adjustments)
                                 orig_folio_committed_amount_cents: crores * CRORE * 100, onboarding_completed: folio_id != ONBOARDING_INCOMPLETE,
                                 notes: NOTE)
      result = CapitalCommitmentCreate.call(capital_commitment: cc)
      raise "Commitment #{folio_id}: #{cc.errors.full_messages.to_sentence.presence || result[:errors]}" unless result.success?

      @folios[folio_id] = cc
    end
    say("  #{@folios.size} commitments, #{inr(LPS.sum(&:last) * CRORE)}")
  end

  def new_investor(name)
    # Short and stable: the investor-entity email lock name (MySQL GET_LOCK) is capped at 64 characters
    email = "demo+#{Digest::MD5.hexdigest(name).first(10)}@example.com"
    investor_entity = Entity.find_by(primary_email: email) || Entity.create!(name:, entity_type: "Investor", primary_email: email)
    @entity.investors.create!(investor_name: name, investor_entity:, category: "LP", primary_email: email, city: "Mumbai")
  end

  def approved_kyc(investor, individual)
    tax_id = Digest::MD5.hexdigest(investor.investor_name)[0, 10].upcase
    kyc = InvestorKyc.new(entity: @entity, investor:, full_name: investor.investor_name, kyc_type: individual ? "individual" : "non_individual",
                          residency: "domestic", PAN: tax_id, address: "1 Demo Street, Mumbai", corr_address: "1 Demo Street, Mumbai",
                          bank_name: "Demo Bank", bank_branch: "Mumbai", bank_account_type: "Current",
                          bank_account_number: tax_id.to_i(16).to_s.first(12), ifsc_code: "DEMO0000001", birth_date: Date.new(1975, 1, 1),
                          verified: true, submission_status: "verified")
    kyc.skip_cf_before_save = true if kyc.respond_to?(:skip_cf_before_save=)
    kyc.save!
    kyc
  end

  # Buys through PortfolioInvestmentCreate (which records the cost valuation), then quarter-end
  # valuations for every company but the one left stale (P7)
  def create_portfolio
    COMPANIES.each do |name, sector, shares, crores, bought, growth, revalued|
      bought_on = @today + bought
      pc, instrument = EvergreenDemoPortfolio.buy(@fund, name:, shares:, bought_on:, cost_cents: crores * CRORE * 100, sector:, notes: NOTE)
      @esign_company = pc if name == ESIGN_COMPANY
      next unless revalued

      cost_ps = (crores * CRORE * 100).to_d / shares
      QUARTER_ENDS.select { |d| d > bought_on }.each_with_index do |date, i|
        per_share = (cost_ps * ((1 + growth)**(i + 1))).round(2)
        EvergreenDemoPortfolio.value(@fund, pc, instrument, date:, per_share_cents: per_share, shares:)
      end
    end
    say("  Portfolio: #{COMPANIES.map(&:first).join(', ')}")
  end

  # ---------- Build: calls, payments, distribution, document ----------

  def create_call(spec)
    call = CapitalCall.new(entity: @entity, fund: @fund, name: spec[:name], call_basis: "Percentage of Commitment",
                           # Each remittance reads its % from close_percentages[its fund_close] (call_basis_percentage_commitment)
                           percentage_called: spec[:pct], close_percentages: { "First Close" => spec[:pct] }, fund_closes: ["All"], call_date: @today + spec[:call], due_date: @today + spec[:due],
                           # No notices or payment emails: the "sent" flags below are set directly instead
                           send_call_notice_flag: false, send_payment_notification_flag: false, notes: NOTE)
    result = CapitalCallCreate.call(capital_call: call)
    raise "#{spec[:name]}: #{call.errors.full_messages.to_sentence.presence || result[:errors]}" unless result.success?

    approve(call)
    # CapitalCallJob logs and skips a remittance it cannot create, so check every folio got one
    remittances = call.capital_remittances.reload
    raise "#{spec[:name]}: #{remittances.size} remittances generated for #{@folios.size} folios — see the Rails log" if remittances.size != @folios.size

    remittances.each { |cr| settle(cr, spec) }
    say("  #{call.name}: #{call.reload.capital_remittances.group(:status).count.map { |s, n| "#{s} #{n}" }.join(', ')}")
  end

  # As the Approve button does (CapitalCallsController#approve), without its rule check: a new entity has no rules
  def approve(call)
    call.approved = true
    call.approved_by_user = @ops
    result = WithValidationRules.skip { CapitalCallApprove.call(capital_call: call) }
    raise "Approve #{call.name}: #{result[:errors]}" unless result.success?
  end

  # One remittance: mark its notice sent (unless P4), then pay and verify as its folio's outcome says
  def settle(remittance, spec)
    # Notices were "sent" by hand — a one-way flag the app sets when it emails the notice
    remittance.update_column(:notification_sent, true) unless Array(spec[:notice_not_sent]).include?(remittance.folio_id)
    outcome = spec[:folios][remittance.folio_id]
    return if outcome == :unpaid

    # Paid in full five days before the due date (never in the future)
    paid_on = [remittance.capital_call.due_date - 5.days, @today].min
    payment = CapitalRemittancePayment.new(entity: @entity, fund: @fund, capital_remittance: remittance, payment_date: paid_on,
                                           folio_amount_cents: remittance.folio_call_amount_cents + remittance.folio_other_fee_cents,
                                           reference_no: "DEMO-#{remittance.capital_call_id}-#{remittance.folio_id}", notes: NOTE)
    result = CapitalRemittancePaymentCreate.call(capital_remittance_payment: payment)
    raise "Payment #{remittance.folio_id}: #{payment.errors.full_messages.to_sentence.presence || result[:errors]}" unless result.success?
    return if outcome == :unverified

    # Verify toggles the flag; the payment's after-commit has just left it unverified
    result = CapitalRemittanceVerify.call(capital_remittance: remittance.reload)
    raise "Verify #{remittance.folio_id}: #{result[:errors]}" unless result.success?
  end

  # A ₹5 Cr distribution (part exit from Nilgiri); payments generated by CapitalDistributionJob, all
  # completed except the one left outstanding (P6)
  def create_distribution
    cd = CapitalDistribution.new(entity: @entity, fund: @fund, title: "Distribution 1 — Nilgiri partial exit", distribution_date: @today - 10.days,
                                 distribution_on: "Commitment Percentage", income_cents: 2 * CRORE * 100, cost_of_investment_cents: 3 * CRORE * 100,
                                 reinvestment_cents: 0, generate_payments: true, generate_payments_paid: false, notes: NOTE)
    result = CapitalDistributionCreate.call(capital_distribution: cd)
    raise "Distribution: #{cd.errors.full_messages.to_sentence.presence || result[:errors]}" unless result.success?

    payments = cd.capital_distribution_payments.reload
    raise "Distribution #{cd.id} generated no payments" if payments.empty?

    payments.each do |payment|
      next if payment.folio_id == PAYOUT_INCOMPLETE

      payment.completed = true
      result = CapitalDistributionPaymentUpdate.call(capital_distribution_payment: payment)
      raise "Distribution payment #{payment.folio_id}: #{payment.errors.full_messages.to_sentence.presence || result[:errors]}" unless result.success?
    end
    say("  #{cd.title}: #{payments.size} payments, #{PAYOUT_INCOMPLETE} not completed")
  end

  # A portfolio-company document marked as sent for e-sign 15 days ago (P8). Portfolio-company
  # documents are the ones the MCP list_documents tool can see. The e-sign columns are written
  # directly so no e-sign provider is ever called.
  def create_stuck_esign_document
    doc = Document.new(entity: @entity, owner: @esign_company, name: ESIGN_DOC, orignal: true, user: @ops,
                       file: File.open(Rails.public_path.join('sample_uploads/address_proof.pdf')))
    doc.save!
    stuck_at = ESIGN_STUCK_DAYS.days.ago
    doc.update_columns(esign_status: "requested", sent_for_esign: true, sent_for_esign_date: stuck_at, created_at: stuck_at)
    say("  Document #{doc.id}: #{doc.name} (e-sign requested #{stuck_at.to_date})")
  end

  # ---------- Build: open fund, MCP access ----------

  # The open-ended fund, built exactly as evergreen:seed_demo_fund builds one, then given its name
  def build_open
    say("  Open-ended fund (EvergreenDemoFund):")
    EvergreenDemoFund.new(entity: @entity, currency: "INR", execute: true, out: @out).run
    @open_fund = @entity.funds.where.not(id: @fund.id).order(:id).last
    @open_fund.update!(name: OPEN_FUND_NAME)
  end

  # The bot sees a fund only through an access right of its own (FundScopes.for_employee), and a
  # portfolio company likewise (Investor.for_employee joins the company's own access rights) —
  # without the second, list_portfolio_companies / list_valuations / list_documents return nothing
  def grant_bot_access
    [@fund, @open_fund].each do |fund|
      AccessRight.find_or_create_by!(owner: fund, access_type: "Fund", user_id: @bot.id, entity_id: @entity.id)
    end
    @entity.investors.portfolio_companies.find_each do |pc|
      AccessRight.find_or_create_by!(owner: pc, access_type: "Investor", user_id: @bot.id, entity_id: @entity.id)
    end
  end

  # The token Paperclip presents as `Authorization: Bearer …` — bound to this entity and the
  # Paperclip client, read scope, 30 days (the Doorkeeper default lifetime)
  def issue_token
    app = Doorkeeper::Application.find_or_create_by!(name: MCP_CLIENT) do |a|
      a.redirect_uri = "http://localhost:3100/oauth/callback"
      a.scopes = "read"
    end
    @token = Doorkeeper::AccessToken.create!(application: app, resource_owner_id: @bot.id, entity_id: @entity.id, scopes: "read",
                                             expires_in: 30.days.to_i)
  end

  # ---------- Output ----------

  def print_summary
    say("Done: #{@entity.name} — entity #{@entity.id}")
    say("  #{@fund.name}: /funds/#{@fund.id}")
    say("  #{@open_fund.name}: /funds/#{@open_fund.id}")
    say("  Log in as #{ops_email} / password")
    say("  MCP bearer token for #{bot_email} (expires #{(@token.created_at + @token.expires_in.seconds).to_date}):")
    say("    #{@token.token}")
    say("  Planted problems:")
    planted.each { |id, text| say("    #{id} #{text}") }
  end

  def domain
    "#{@name.parameterize}.test"
  end

  def ops_email
    "ops@#{domain}"
  end

  def bot_email
    "paperclip-bot@#{domain}"
  end

  def inr(rupees)
    "INR #{number_to_delimited(rupees)}"
  end

  def say(msg)
    @out.puts(msg)
  end
end
