# Clears a user's two-factor METHOD back to "none" so they pick a fresh one at their next
# login, without ever switching two-factor OFF.
#
# WHY THIS EXISTS
#
# `two_factor_mode` is written only when an enrollment code verifies (the verify_* actions in
# Users::TwoFactorController), reachable only while the mode is still nil — and before this
# operation existed nothing anywhere cleared it. A user who
# picked WhatsApp on day one could never move to an authenticator app, and a user who lost
# their phone was locked out with no recovery path other than a developer editing the row.
#
# WHAT A RESET DOES (and deliberately does not do)
#
#   * two_factor_mode     -> nil   TwoFactorDispatch already routes nil-mode users to the
#                                  mode-selection screen, so the login flow needs no change.
#   * otp_secret          -> nil   The old authenticator entry / in-flight WhatsApp codes die.
#                                  A new secret is generated by the enrollment screens.
#   * consumed_timestep   -> nil   Anti-replay bookkeeping for the OLD secret. Left set,
#                                  devise-two-factor passes it to ROTP as `after:` and the
#                                  first code of the NEW secret is rejected whenever
#                                  re-enrolment lands in the same 30-second window as the
#                                  last verified login.
#   * two_factor_enabled  -> UNCHANGED. Two-factor is never silently disabled by a reset;
#                                  the user cannot get in until a new method is verified.
#   * two_factor_reset_at / _by_id -> stamped, so the mode-selection banner and the
#                                  confirmation email can say when and by whom.
#
# WHO MAY CALL IT
#
# Authorization is the controller's job (UserPolicy#reset_two_factor?). This operation
# only enforces the one rule that belongs to the action itself: a SELF-SERVICE reset must
# re-prove the password, because a hijacked browser session must not be able to weaken
# the account's second factor. Administrator resets skip that step — the admin's own
# authenticated session plus the policy is the gate, mirroring UsersController#login_as.
#
# Usage:
#   result = TwoFactorReset.call(user: target, actor: current_user, password: params[:password], message: params[:message])
#   result.success? / result[:errors]
#
# See docs/modules/two_factor_auth/two_factor_authentication.md, "Resetting the two-factor method".
class TwoFactorReset < Trailblazer::Operation
  step :ensure_resettable
  step :verify_password_if_self
  # Single failure handler: a failing step above jumps to the left track and lands here.
  left :handle_errors, Output(:failure) => End(:failure)
  step :clear_method
  step :notify_user

  # Nothing to reset for a user without a method: they are already headed for the
  # mode-selection screen. Refusing keeps the audit trail honest (no no-op "resets").
  def ensure_resettable(ctx, user:, **)
    if !user.two_factor_enabled?
      ctx[:errors] = "Two-factor authentication is not enabled for this user."
      false
    elsif user.two_factor_mode.blank?
      ctx[:errors] = "No two-factor method is set up yet — nothing to reset."
      false
    else
      true
    end
  end

  # Step-up check for the self-service path only. `password` is ignored for admin resets.
  def verify_password_if_self(ctx, user:, actor:, **)
    return true unless self_reset?(user, actor)

    if user.valid_password?(ctx[:password].to_s)
      true
    else
      ctx[:errors] = "The password you entered is incorrect."
      false
    end
  end

  def handle_errors(ctx, **)
    Rails.logger.warn "[TwoFactorReset] refused: #{ctx[:errors]}"
    false
  end

  # The actual reset. `audit_comment` rides along on the audited row so the audit log
  # records who asked for it and why, alongside the two_factor_mode change itself.
  def clear_method(ctx, user:, actor:, **)
    ctx[:previous_mode] = user.two_factor_mode
    ActiveRecord::Base.connected_to(role: :writing) do
      # The method itself is forgotten by the same code the disable toggle uses; this
      # operation only adds the who/when stamp and the audit comment.
      user.forget_two_factor_method
      user.update!(
        two_factor_reset_at: Time.current,
        two_factor_reset_by_id: actor.id,
        audit_comment: "Two-factor method reset from #{ctx[:previous_mode]} by #{self_reset?(user, actor) ? 'self' : "user ##{actor.id}"}"
      )
    end
    Rails.logger.info "[TwoFactorReset] user_id=#{user.id} previous_mode=#{ctx[:previous_mode]} actor_id=#{actor.id}"
    true
  end

  # Security notification. Sent for both paths: a self reset confirms the action to the
  # owner, an admin reset warns them if they never asked for it.
  def notify_user(ctx, user:, actor:, **)
    # entity_id + user_id are what ApplicationMailer#setup_defaults keys on to work out the
    # from address and to honour the entity's sandbox-email setting.
    UserMailer.with(
      entity_id: user.entity_id,
      user_id: user.id,
      actor_id: actor.id,
      previous_mode: ctx[:previous_mode],
      message: ctx[:message].to_s.strip.presence
    ).two_factor_reset.deliver_later
    true
  end

  private

  def self_reset?(user, actor)
    user.id == actor.id
  end
end
