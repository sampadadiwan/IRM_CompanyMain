class CapitalRemittanceDocJob < DocGenJob
  def templates(model = nil)
    if @template_id.present?
      [Document.find(@template_id)]
    elsif model.present?
      model.capital_commitment.templates("Call Template")
    else
      @fund.documents.templates.where(owner_tag: "Call Template")
    end
  end

  def models
    if @capital_remittance_id.present?
      [CapitalRemittance.find(@capital_remittance_id)]
    else
      @capital_call.capital_remittances
                   .includes(:fund, :entity, :investor, :investor_kyc, { capital_commitment: :fund },
                             :documents, :form_type, :document_folder)
    end
  end

  def validate(capital_remittance)
    return false, "No Capital Remittance found" if capital_remittance.blank?
    return false, "InvestorKyc not verified" if capital_remittance.investor_kyc.blank? || !capital_remittance.investor_kyc.verified

    [true, ""]
  end

  def generator
    CapitalRemittanceDocGenerator
  end

  def cleanup_previous_docs(model, template)
    # Delete any existing signed documents
    model.documents.not_templates.where(name: template.name).find_each(&:destroy)
  end

  # Re-checks the call's journey once generation finishes (capital-call-journey): an undo when it
  # replaced notices, otherwise ordinary progress. Worked examples E7, E20 — openspec/changes/archive/2026-10-02-capital-call-journey/design.md#worked-examples
  def evaluate_journey(had_notices, started_at)
    actor = User.find_by(id: @user_id)
    if had_notices
      @capital_call.journey_undo_evaluate(note: "Notices regenerated by #{actor&.full_name || 'a user'}", actor:, started_at:)
    else
      WorkflowEvaluator.for(@capital_call, cause: :progress, actor:)
    end
  rescue StandardError => e
    Rails.logger.error("[CapitalRemittanceDocJob] journey evaluation for call #{@capital_call&.id}: #{e.message}")
  end

  def generate_doc_name(model, template, _start_date, _end_date)
    "#{template.name} - #{model}"
  end

  # This is idempotent, we should be able to call it multiple times for the same CapitalRemittance
  def perform(capital_call_id, capital_remittance_id, user_id, template_id: nil, options: {})
    @capital_call_id = capital_call_id
    @capital_call = CapitalCall.find(capital_call_id)
    @fund = @capital_call.fund
    @capital_remittance_id = capital_remittance_id

    @start_date = Time.zone.now
    @end_date = Time.zone.now
    @user_id = user_id
    @template_id = template_id
    # custom field value can be kyc or folio
    options[:call_notice_per_kyc] = @fund.kyc_level_data_gen?

    # Notices that existed before this run: regenerating them is an undoing action
    had_notices = Document.exists?(owner_type: "CapitalRemittance", owner_id: @capital_call.capital_remittances.select(:id),
                                   owner_tag: "Generated")
    journey_started_at = Time.current

    Chewy.strategy(:sidekiq) do
      generate(@start_date, @end_date, @user_id, options: options) if valid_inputs
    end

    evaluate_journey(had_notices, journey_started_at)
    @error_msg
  end
end
