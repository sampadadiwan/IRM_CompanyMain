class CapitalDistributionPaymentDocJob < DocGenJob
  # Returns the Distribution Template using the id , or but name using the model;s commitment or the fund
  def templates(model = nil)
    if @template_id.present?
      [Document.find(@template_id)]
    elsif model.present?
      model.capital_commitment.templates("Distribution Template")
    else
      @fund.documents.templates.where(owner_tag: "Distribution Template")
    end
  end

  # Returns the models to generate documents for
  # If @capital_distribution_payment_id is present, it returns that specific payment
  # Otherwise, it returns all payments for the capital distribution
  def models
    if @capital_distribution_payment_id.present?
      [CapitalDistributionPayment.find(@capital_distribution_payment_id)]
    else
      @capital_distribution.capital_distribution_payments
                           .includes(:fund, :entity, :investor, :investor_kyc, { capital_commitment: :fund },
                                     :documents, :form_type, :document_folder)
    end
  end

  # Validates that the capital distribution payment is present and that the investor KYC is verified
  def validate(capital_distribution_payment)
    return false, "No Capital Distribution Payment found" if capital_distribution_payment.blank?
    return false, "Investor Kyc not verified" if capital_distribution_payment.investor_kyc.blank? || !capital_distribution_payment.investor_kyc.verified

    [true, ""]
  end

  def generator
    CapitalDistributionPaymentDocGenerator
  end

  def cleanup_previous_docs(model, template)
    # Delete any existing signed documents
    model.documents.not_templates.where(name: template.name).find_each(&:destroy)
  end

  def generate_doc_name(model, template, _start_date, _end_date)
    "#{template.name} - #{model.investor_name}"
  end

  # This is idempotent, we should be able to call it multiple times for the same CapitalDistributionPayment
  def perform(capital_distribution_id, capital_distribution_payment_id, user_id, template_id: nil, options: {})
    @capital_distribution_id = capital_distribution_id
    @capital_distribution = CapitalDistribution.find(capital_distribution_id)
    @fund = @capital_distribution.fund
    @capital_distribution_payment_id = capital_distribution_payment_id

    @start_date = Time.zone.now
    @end_date = Time.zone.now
    @user_id = user_id
    @template_id = template_id

    # If call_notice_on is set to kyc in the fund json_fields then notice will be generated with KYC level data
    options[:dist_notice_per_kyc] = @fund.kyc_level_data_gen?

    # Taken before generating: whether this replaces notices decides progress vs undo below.
    # Skipped entirely for a distribution without a journey (no journey, no cost).
    journey_started_at = Time.current
    journey = journey?
    had_notices = journey && generated_notices.exists?

    Chewy.strategy(:sidekiq) do
      generate(@start_date, @end_date, @user_id, options: options) if valid_inputs
    end

    evaluate_journey(had_notices, journey_started_at) if journey
    @error_msg
  end

  private

  # The distribution has a live journey to re-check
  def journey?
    WorkflowInstance.evaluated.where(workflowable: @capital_distribution).where.not(status: :archived).exists?
  end

  # Generated notices on the payments this run covers: one payment (its own Generate Documents) or all.
  # Only replacing notices in this scope makes the run an undo — a single-payment run on a distribution
  # whose other payments already have notices is ordinary progress.
  # Worked examples E11 — openspec/changes/archive/2026-10-02-capital-distribution-journey/design.md#worked-examples
  def generated_notices
    payments = @capital_distribution.capital_distribution_payments
    payments = payments.where(id: @capital_distribution_payment_id) if @capital_distribution_payment_id.present?
    Document.where(owner_type: "CapitalDistributionPayment", owner_tag: "Generated", owner_id: payments.select(:id))
  end

  # Re-checks the distribution's journey once generation finishes: an undo when it replaced notices
  # (approvals of the old ones no longer stand), otherwise ordinary progress. No-op without a journey.
  # Worked examples H2, E11 — openspec/changes/archive/2026-10-02-capital-distribution-journey/design.md#worked-examples
  def evaluate_journey(had_notices, started_at)
    actor = User.find_by(id: @user_id)
    if had_notices
      @capital_distribution.journey_undo_evaluate(note: "Notices regenerated by #{actor&.full_name || 'a user'}", actor:, started_at:)
    else
      @capital_distribution.journey_progress!(actor:)
    end
  end
end
