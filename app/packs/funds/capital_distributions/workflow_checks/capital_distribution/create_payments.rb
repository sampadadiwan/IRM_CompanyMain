# 1. Create payments — generated distributions: every commitment the fund had when the distribution
# was created has a payment (what CapitalDistributionJob iterates; a commitment admitted later is
# not expected to be paid by this distribution). Uploaded payments (Upload basis, or an import with
# Generate Payments off): the distribution has payments and every upload that created them finished
# without errors — Upload distributions often pay only some commitments.
# Worked examples H2, E4, E10 — openspec/changes/archive/2026-10-02-capital-distribution-journey/design.md#worked-examples
module WorkflowChecks
  module CapitalDistribution
    class CreatePayments < WorkflowChecks::Base
      include Support

      self.key = "capital_distribution.create_payments"
      self.label = "Create payments"
      self.workflowable_type = "CapitalDistribution"

      def call(dist)
        generated?(dist) ? generated(dist) : uploaded(dist)
      end

      private

      # Payments are generated by the app unless the basis is Upload or generation is switched off
      def generated?(dist)
        dist.generate_payments && !dist.distribution_on_upload?
      end

      def generated(dist)
        expected = dist.fund.capital_commitments.where(created_at: ..dist.created_at)
        expected_count = expected.count
        missing = expected.where.not(id: payments(dist).select(:capital_commitment_id)).count
        if expected_count.zero? || missing.positive?
          return fail_with(message: "#{expected_count - missing} of #{expected_count} payments created",
                           action_label: "View payments", action_path: distribution_path(dist), action_target: PAYMENTS_TAB)
        end

        done(dist, "#{payment_count(dist)} created")
      end

      def uploaded(dist)
        unless payments(dist).exists?
          return fail_with(message: "No payments uploaded yet", action_label: "View payments",
                           action_path: distribution_path(dist), action_target: PAYMENTS_TAB)
        end

        uploads = ::ImportUpload.where(id: payments(dist).where.not(import_upload_id: nil).select(:import_upload_id))
        return fail_with(message: "Payment upload in progress") if uploads.where(status: nil).where("processed_row_count < total_rows_count").exists?(created_at: 1.day.ago..)
        # A failed row only counts in failed_row_count: the upload still ends "Completed" (and the
        # journey may be re-checked before the status is saved), so both are checked
        if uploads.where.not(status: [nil, "", "Completed"]).or(uploads.where(failed_row_count: 1..)).exists?
          return fail_with(message: "Payment upload failed — fix and re-import", action_label: "View payments",
                           action_path: distribution_path(dist), action_target: PAYMENTS_TAB)
        end

        done(dist, "#{payment_count(dist)} uploaded")
      end

      def payment_count(dist)
        count = payments(dist).count
        "#{count} #{'payment'.pluralize(count)}"
      end

      def done(dist, message)
        pass(message:, passed_since: payments(dist).maximum(:created_at), fresh_since: payments(dist).minimum(:created_at))
      end
    end
  end
end
